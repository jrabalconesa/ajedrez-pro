import assert from 'node:assert/strict';
import {Chess} from 'chess.js';
import {ownThreats,reviewPositions,reviewEntry,legalLine} from '../lib/review';
import {fresh,mutate} from '../lib/chess-state';
import {transitionGame} from '../lib/game-operations';
const c=new Chess(),start=c.fen();
assert.equal(reviewPositions(start,['e4','e5','Nf3']).length,4);
assert.throws(()=>reviewPositions(start,['e5']));
assert.throws(()=>legalLine(start,'e2e5'));
assert.equal(ownThreats(start,'w').length,0);
let threats=ownThreats('4k3/8/8/4p3/3Q4/8/8/4K3 w - - 0 1','w');
assert.equal(threats.find(t=>t.square==='d4')?.danger,true,'Una dama atacada por un peón pierde material');
threats=ownThreats('4k3/8/8/4p3/3P4/2P5/8/4K3 w - - 0 1','w');
assert.equal(threats.find(t=>t.square==='d4')?.danger,false,'Peón defendido: el intercambio no gana material');
threats=ownThreats('4k3/8/8/8/4R3/8/8/4K3 b - - 0 1','b');
assert.equal(threats.find(t=>t.square==='e8')?.danger,true,'Funciona jugando negras y detecta jaque');
threats=ownThreats('4k3/4n3/8/3Q4/8/8/8/4R1K1 w - - 0 1','w');
assert.equal(threats.find(t=>t.square==='d5')?.danger,false,'El caballo clavado ataca geométricamente pero no puede capturar legalmente');
const result=(move:string,cp:number,pv=move)=>({move,evaluation:{cp,depth:12,pv,complete:true},lines:[]});
const bad=reviewEntry(start,'f3',result('e2e4',30,'e2e4 e7e5'),result('e7e5',210,'e7e5 g2g4'));
assert.equal(bad.grade,'bad');assert.equal(bad.loss,240);assert.ok(bad.reply.includes('e5'));
const blackFen=reviewPositions(start,['f3','e5','g4'])[3].fen;
const mate=reviewEntry(blackFen,'Qh4#',result('d8h4',99999),null);
assert.equal(mate.grade,'good');assert.equal(mate.color,'b');assert.equal(mate.highlight,true);assert.match(mate.message,/jaque mate/);
let g=fresh();for(const move of ['f3','e5','g4','Qh4#'])g=mutate(g,'move',{move});
const history=[...g.history];reviewPositions(g.initialFen,g.history);assert.deepEqual(g.history,history,'Reproducir no modifica la partida');
const sought=transitionGame(g,'seek',{cursor:2}).active;
const fork=transitionGame(sought,'fork').active;assert.notEqual(g.id,fork.id);assert.deepEqual(g.history,history);assert.equal(fork.history.length,2);assert.equal(fork.importedResult,undefined);
console.log('Revisión: reproducción, variantes, valoración desde ambos bandos, mate, ataques defendidos y clavadas OK');
